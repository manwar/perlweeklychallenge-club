use v5.28;
sub f {
    eval join ' eq ',
         map s/ ^(.{0,10000}).* / '$1'       /xr,
         map s/ \((.+)\)        / $1 x 20000 /xer,
         map s/ \(0+\)          /            /xr,
         map s/ (\d+)\.9*\(9+\) / ($1+1)."." /xer,
         @_
}
say pop(@$_) == f(@$_) ? "ok" : "ERROR" for
[ "0.(12)",    "0.(121)"    =>  0 ], #false
[ "0.1(23)",   "0.12(32)"   =>  1 ], #true 
[ "0.1(234)",  "0.12(342)"  =>  1 ], #true 
[ "12.99(99)", "13."        =>  1 ], #true 
[ "0.(123)",   "0.1(231)"   =>  1 ]; #true
