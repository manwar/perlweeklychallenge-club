sub f {
    my($n, $b) = @_;
    $n < 0  ? '-' . f( -$n, $b )
  : $n == 0 ? @_ > 2 ? '' : '0'
  : f( int $n / $b, $b, 1 ) . ['0'..'9','A'..'Z','a'..'z','+','/']->[$n % $b]
}

printf "%-20s = %-7s   %s\n", "f($$_[0],$$_[1])", f( @$_[0,1] ), f( @$_[0,1] ) eq $$_[2] ? "ok" : "ERROR" for
