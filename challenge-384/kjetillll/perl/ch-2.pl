sub f {
    my $s = shift;
    !length($s) ? () : ( $s =~ / ^ (.) \1* (??{ (1 - $1) x length $& }) /x ? "$&" : (), f( substr $s, 1 ) )
}

#----tests
print "@{[ @f = f( shift @$_ ) ]}" eq "@{[ @$_ ]}" ? "ok" : "ERROR", " @f\n" for
